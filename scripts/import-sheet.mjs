// Moves the data of the old Google Sheet system into the new database.
//
// 1. In the Google Sheet, open each tab and choose File → Download → Comma Separated Values (.csv):
//      Departments  →  scripts/input/Departments.csv
//      Employees    →  scripts/input/Employees.csv
//      Leave_Requests → scripts/input/Leave_Requests.csv
// 2. Run:   npm run import:sheet              (dates like 26/10/2026)
//      or:  npm run import:sheet -- --mdy     (dates like 10/26/2026)
//      add  --offset=+05:30  for the sheet's time zone (default Sri Lanka)
// 3. Load:  npx wrangler d1 execute able-leave-db --local  --file=scripts/output/import.sql   (your laptop)
//           npx wrangler d1 execute able-leave-db --remote --file=scripts/output/import.sql   (live)
//
// Safe to run again: rows that already exist are skipped (INSERT OR IGNORE).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const inputDir = join(here, 'input');
const outputDir = join(here, 'output');
const MDY = process.argv.includes('--mdy');
const MONTHS = { jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, oct: 10, nov: 11, dec: 12 };

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (ch === '"') quoted = false; else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); rows.push(row); row = []; cell = '';
    } else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim() !== ''));
}

function readCsv(name) {
  const file = join(inputDir, `${name}.csv`);
  if (!existsSync(file)) { console.log(`- ${name}.csv not found, skipped`); return []; }
  const rows = parseCsv(readFileSync(file, 'utf8').replace(/^﻿/, ''));
  console.log(`- ${name}.csv: ${rows.length - 1} row(s)`);
  return rows.slice(1);
}

const sql = (v) => (v === null || v === undefined || v === '' ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const text = (v) => `'${String(v ?? '').trim().replace(/'/g, "''")}'`;
const pad = (n) => String(n).padStart(2, '0');

// "2026-10-26", "26/10/2026", "26 Oct 2026", "26-Oct-2026" (+ optional time) -> { date, time }
function parseDate(raw) {
  const s = String(raw || '').trim();
  if (!s) return null;
  let m = /^(\d{4})-(\d{1,2})-(\d{1,2})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2}))?)?/.exec(s);
  if (m) return { date: `${m[1]}-${pad(m[2])}-${pad(m[3])}`, time: m[4] ? `${pad(m[4])}:${m[5]}:${m[6] || '00'}` : '' };
  m = /^(\d{1,2})[/.](\d{1,2})[/.](\d{4})(?:\s+(\d{1,2}):(\d{2})(?::(\d{2}))?)?/.exec(s);
  if (m) {
    const [d, mo] = MDY ? [m[2], m[1]] : [m[1], m[2]];
    return { date: `${m[3]}-${pad(mo)}-${pad(d)}`, time: m[4] ? `${pad(m[4])}:${m[5]}:${m[6] || '00'}` : '' };
  }
  m = /^(\d{1,2})[\s-]([A-Za-z]{3})[a-z]*[\s-,]+(\d{4})(?:\s+(\d{1,2}):(\d{2})(?::(\d{2}))?)?/.exec(s);
  if (m && MONTHS[m[2].toLowerCase()]) {
    return { date: `${m[3]}-${pad(MONTHS[m[2].toLowerCase()])}-${pad(m[1])}`, time: m[4] ? `${pad(m[4])}:${m[5]}:${m[6] || '00'}` : '' };
  }
  return null;
}
// Sheet times are local time; stored as UTC. Default +05:30 (Sri Lanka); change with --offset=+04:00
const offArg = (process.argv.find((a) => a.startsWith('--offset=')) || '--offset=+05:30').slice(9);
const offMatch = /^([+-])(\d{2}):(\d{2})$/.exec(offArg) || ['', '+', '05', '30'];
const OFFSET_MIN = (offMatch[1] === '-' ? -1 : 1) * (Number(offMatch[2]) * 60 + Number(offMatch[3]));
function isoOf(raw) {
  const p = parseDate(raw);
  if (!p) return null;
  const local = Date.parse(`${p.date}T${p.time || '00:00:00'}Z`);
  return isNaN(local) ? null : new Date(local - OFFSET_MIN * 60000).toISOString();
}

const out = ['-- Generated by scripts/import-sheet.mjs', 'PRAGMA defer_foreign_keys = true;'];

// ---- Departments: A name, B head names, C head emails (comma separated, same order)
for (const r of readCsv('Departments')) {
  const name = (r[0] || '').trim();
  if (!name) continue;
  out.push(`INSERT OR IGNORE INTO departments (name) VALUES (${text(name)});`);
  const emails = String(r[2] || '').split(/[,;\s]+/).map((x) => x.trim().toLowerCase()).filter((x) => /^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(x));
  const names = String(r[1] || '').split(/[,;\n]+/).map((x) => x.trim()).filter(Boolean);
  emails.forEach((email, i) => {
    out.push(`INSERT OR IGNORE INTO users (email, name, role, status, must_change) VALUES (${text(email)}, ${text(names[i] || email)}, 'head', 'active', 1);`);
    out.push(`INSERT OR IGNORE INTO department_heads (department_id, user_id) SELECT d.id, u.id FROM departments d, users u WHERE d.name = ${text(name)} AND u.email = ${text(email)};`);
  });
}

// ---- Employees: A number, B name, C department, D email, E status
for (const r of readCsv('Employees')) {
  const no = (r[0] || '').trim().toUpperCase();
  if (!no) continue;
  const status = /inactive/i.test(r[4] || '') ? 'Inactive' : 'Active';
  out.push(`INSERT OR IGNORE INTO employees (emp_no, name, email, department_id, status) VALUES (${text(no)}, ${text(r[1])}, ${text((r[3] || '').toLowerCase())},
    (SELECT id FROM departments WHERE name = ${text(r[2])} COLLATE NOCASE), '${status}');`);
}

// ---- Leave_Requests: the 22 columns of the old sheet
// A ID, B Submitted, C EmpNo, D Email, E Name, F Dept, G Type, H From, I To, J DayType, K Out, L Return, M Days, N Hours,
// O Reason, P STATUS, Q Remark, R By, S Time, T Notes, U Response ID, V Token
let skipped = 0;
for (const r of readCsv('Leave_Requests')) {
  const id = (r[0] || '').trim();
  const from = parseDate(r[7]);
  const to = parseDate(r[8]) || from;
  if (!id || !from) { skipped++; continue; }
  const status = ['Pending', 'Approved', 'Rejected', 'Cancelled'].find((s) => s.toLowerCase() === String(r[15] || '').trim().toLowerCase()) || 'Pending';
  const dayType = /short/i.test(r[9]) ? 'Short Leave' : /half/i.test(r[9]) ? 'Half Day' : 'Full Day';
  const groupNo = id.replace(/-\d+$/, '');
  const empNo = (r[2] || '').trim();
  out.push(`INSERT OR IGNORE INTO leave_requests (request_no, group_no, employee_id, emp_no, emp_name, emp_email, department_id, department, leave_type,
    from_date, to_date, day_type, out_time, return_time, days, hours, reason, status, remark, decided_by, decided_at, notes, token, submitted_at)
    VALUES (${text(id)}, ${text(groupNo)}, (SELECT id FROM employees WHERE emp_no = ${text(empNo)} COLLATE NOCASE), ${text(empNo)}, ${text(r[4])},
    ${text((r[3] || '').toLowerCase())}, (SELECT id FROM departments WHERE name = ${text(r[5])} COLLATE NOCASE), ${text(r[5])}, ${text(r[6])},
    '${from.date}', '${to.date}', '${dayType}', ${text(String(r[10] || '').slice(0, 5))}, ${text(String(r[11] || '').slice(0, 5))},
    ${Number(r[12]) || 0}, ${sql(r[13] === '' ? null : Number(r[13]) || null)}, ${text(r[14])}, '${status}', ${text(r[16])}, ${text(r[17])},
    ${sql(isoOf(r[18]))}, ${text(r[19])}, '${randomBytes(24).toString('hex')}', ${sql(isoOf(r[1]) || `${from.date}T00:00:00.000Z`)});`);
}

// keep request numbers going after the imported ones (R26Oct001 ...)
out.push(`INSERT INTO counters (key, value)
  SELECT substr(group_no, 1, 6), MAX(CAST(substr(group_no, 7, 3) AS INTEGER)) FROM leave_requests WHERE group_no GLOB 'R[0-9][0-9][A-Z][a-z][a-z][0-9]*' GROUP BY substr(group_no, 1, 6)
  ON CONFLICT(key) DO UPDATE SET value = MAX(value, excluded.value);`);

mkdirSync(outputDir, { recursive: true });
const file = join(outputDir, 'import.sql');
writeFileSync(file, `${out.join('\n')}\n`);
console.log(`\nWritten: ${file}${skipped ? `\n${skipped} request row(s) skipped (no ID or date not readable).` : ''}`);
console.log('Next: npx wrangler d1 execute able-leave-db --local --file=scripts/output/import.sql   (or --remote for the live database)');
